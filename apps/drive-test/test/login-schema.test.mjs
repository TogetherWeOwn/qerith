import { applyD1Migrations } from 'cloudflare:test';
import { env } from 'cloudflare:workers';
import { expect, it } from 'vitest';

it('upgrades seeded members and replays the real migration directory', async () => {
  const prior = env.DRIVE_MIGRATIONS.filter(({ name }) => name < '0010_login_generations.sql');
  await applyD1Migrations(env.DB, prior);
  await env.DB.exec("INSERT INTO drive_principals VALUES ('member', 'member', 'active')");
  const ledger = async () => (await env.DB.prepare('SELECT id, name FROM d1_migrations ORDER BY id').all()).results;
  const before = await ledger();
  await applyD1Migrations(env.DB, env.DRIVE_MIGRATIONS);
  const generation = await env.DB.prepare("SELECT generation FROM drive_login_generations WHERE principal_id = 'member'").first();
  expect(generation.generation).toMatch(/^[a-f0-9]{64}$/);
  await applyD1Migrations(env.DB, env.DRIVE_MIGRATIONS);
  const after = await ledger();
  expect(after.slice(0, before.length)).toEqual(before);
  expect(after.map(({ name }) => name)).toEqual(env.DRIVE_MIGRATIONS.map(({ name }) => name));
  expect(await env.DB.prepare("SELECT generation FROM drive_login_generations WHERE principal_id = 'member'").first()).toEqual(generation);
  await env.DB.exec("INSERT INTO drive_principals (id, role, status) VALUES ('new-member', 'member', 'active')");
  const newGeneration = await env.DB.prepare("SELECT generation FROM drive_login_generations WHERE principal_id = 'new-member'").first();
  expect(newGeneration.generation).toMatch(/^[a-f0-9]{64}$/);
  await env.DB.exec(`INSERT INTO drive_bound_ceremonies VALUES ('login', 'authentication', 'auth', 9999999999999);
    INSERT INTO drive_bound_ceremonies VALUES ('register', 'registration', 'reg', 9999999999999);
    UPDATE drive_principals SET status = 'active' WHERE id = 'member'`);
  expect(await env.DB.prepare("SELECT generation FROM drive_login_generations WHERE principal_id = 'member'").first()).toEqual(generation);
  expect((await env.DB.prepare('SELECT purpose FROM drive_bound_ceremonies ORDER BY purpose').all()).results).toHaveLength(2);
  await env.DB.exec("UPDATE drive_principals SET status = 'revoked' WHERE id = 'member'");
  const revoked = await env.DB.prepare("SELECT generation FROM drive_login_generations WHERE principal_id = 'member'").first();
  expect(revoked.generation).not.toBe(generation.generation);
  expect((await env.DB.prepare('SELECT purpose FROM drive_bound_ceremonies').all()).results).toEqual([{ purpose: 'registration' }]);
  await env.DB.exec("UPDATE drive_principals SET status = 'active' WHERE id = 'member'");
  expect((await env.DB.prepare("SELECT generation FROM drive_login_generations WHERE principal_id = 'member'").first()).generation).not.toBe(revoked.generation);
  expect(await env.DB.prepare("SELECT generation FROM drive_login_generations WHERE principal_id = 'new-member'").first()).toEqual(newGeneration);
});
